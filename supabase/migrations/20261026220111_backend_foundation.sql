SET lock_timeout = '4s';

-- FR-001: the single runtime role is renamed in place so grants and policies keep its OID.
-- The password is never set here; the maintainer rotates it after the rename.
DO $$
DECLARE
  has_old boolean := EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'online_runtime');
  has_new boolean := EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_runtime');
BEGIN
  IF has_old AND has_new THEN
    RAISE EXCEPTION 'Both online_runtime and app_runtime exist; resolve the duplicate role manually before applying this migration.';
  ELSIF has_old THEN
    ALTER ROLE online_runtime RENAME TO app_runtime;
  ELSIF NOT has_new THEN
    RAISE EXCEPTION 'Neither online_runtime nor app_runtime exists; apply the earlier migrations first.';
  END IF;
END
$$;

ALTER ROLE app_runtime SET statement_timeout = '5s';
ALTER ROLE app_runtime SET idle_in_transaction_session_timeout = '10s';

-- FR-003/FR-004: deny by default for browser roles and for objects created later.
CREATE SCHEMA IF NOT EXISTS app AUTHORIZATION postgres;
REVOKE ALL ON SCHEMA app FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SCHEMA private FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA app TO app_runtime;

ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA app, private
  REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA app, private
  REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA app, private
  REVOKE ALL ON FUNCTIONS FROM PUBLIC, anon, authenticated;

-- FR-006: one account per professional; RESTRICT keeps account closure out of F0.
CREATE TABLE IF NOT EXISTS app.accounts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_user_id uuid NOT NULL UNIQUE REFERENCES auth.users (id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE app.accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.accounts FORCE ROW LEVEL SECURITY;

-- FR-007: the account context of the current transaction; no SECURITY DEFINER.
CREATE OR REPLACE FUNCTION app.current_account_id()
RETURNS uuid
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = ''
AS $$
  SELECT NULLIF(current_setting('app.account_id', true), '')::uuid
$$;

REVOKE EXECUTE ON FUNCTION app.current_account_id() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION app.current_account_id() TO app_runtime;

-- FR-002/FR-008/FR-009a: SELECT/INSERT only, no UPDATE or DELETE policy, id generated by the database.
DROP POLICY IF EXISTS accounts_select ON app.accounts;
CREATE POLICY accounts_select ON app.accounts
  FOR SELECT TO app_runtime
  USING (
    id = app.current_account_id()
    OR owner_user_id = NULLIF(current_setting('app.user_id', true), '')::uuid
  );

DROP POLICY IF EXISTS accounts_insert ON app.accounts;
CREATE POLICY accounts_insert ON app.accounts
  FOR INSERT TO app_runtime
  WITH CHECK (
    id = app.current_account_id()
    OR owner_user_id = NULLIF(current_setting('app.user_id', true), '')::uuid
  );

REVOKE ALL ON app.accounts FROM PUBLIC, anon, authenticated, app_runtime;
GRANT SELECT ON app.accounts TO app_runtime;
GRANT INSERT (owner_user_id) ON app.accounts TO app_runtime;
